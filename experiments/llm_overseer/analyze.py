"""Tables for the LLM inspector ladder: alpha, beta, confusion, tokens per check, and C1 (protocol.md, section 4).

  python -m experiments.llm_overseer.analyze --judge-dir results/llm_overseer/judge --out notes/llm_overseer/results

Writes <out>/tables.md (human) and <out>/summary.json (read by harvest_runs.py).
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from overseer.llm import subset as S
from overseer.llm.metrics import c1_class, confusion, effective_penalty, rates
from overseer.llm.models import BY_TAG, LADDER

ORDER = {row[0]: i for i, row in enumerate(LADDER)}


def load_results(judge_dir, meta):
    runs = defaultdict(list)
    for path in sorted(Path(judge_dir).glob("*.jsonl")):
        tag, mode = path.stem.rsplit("_", 1)
        with open(path) as fh:
            for line in fh:
                r = json.loads(line)
                if r.get("error") is None and r["id"] in meta:
                    runs[(tag, mode)].append({**meta[r["id"]], **r})
    return runs


def fmt(x, d=2):
    return "–" if x != x else f"{x:.{d}f}"  # nan -> dash


def ci(pair):
    return f"[{pair[0]:.2f}, {pair[1]:.2f}]" if pair[0] == pair[0] else ""


def analyse(runs):
    rows, c1 = [], []
    eat = (lambda r: r.get("n_eats", 0) > 0)
    for (tag, mode), rs in sorted(runs.items(), key=lambda kv: (ORDER.get(kv[0][0], 99), kv[0])):
        for ds, renderings in (("harvest", S.HARVEST_RENDERINGS), ("bazaar", S.BAZAAR_RENDERINGS)):
            for rend in renderings:
                sub = [r for r in rs if r["dataset"] == ds and r["rendering"] == rend]
                if not sub:
                    continue
                groups = [("all", sub)]
                if ds == "harvest":
                    groups += [(f"w{w}", [r for r in sub if r["window"] == w]) for w in (1, 10, 50)]
                else:
                    groups += [(f, [r for r in sub if r["ftype"] == f]) for f in ("F1", "F2", "F3", "F4", "F5")]
                for name, g in groups:
                    if not g:
                        continue
                    row = dict(model=tag, mode=mode, dataset=ds, rendering=rend, group=name, **rates(g),
                               confusion={f"{k[0]}:{k[1]}": v for k, v in confusion(g).items()})
                    if ds == "harvest":
                        row["beta_eat"] = rates(g, honest_filter=eat)["beta"]
                        row["n_honest_eat"] = rates(g, honest_filter=eat)["n_honest"]
                    else:
                        ro = [r for r in g if r["label"] == 1 and r.get("reasoning_only")]
                        acted = [r for r in g if r["label"] == 1 and not r.get("reasoning_only")]
                        row["alpha_reasoning_only"] = rates(ro)["alpha"] if ro else float("nan")
                        row["alpha_acted"] = rates(acted)["alpha"] if acted else float("nan")
                        row["n_reasoning_only"], row["n_acted"] = len(ro), len(acted)
                    rows.append(row)
                if ds == "harvest":
                    w1 = next(r for r in rows if r["model"] == tag and r["mode"] == mode and r["dataset"] == ds
                              and r["rendering"] == rend and r["group"] == "w1")
                    entry = dict(model=tag, mode=mode, rendering=rend, alpha=w1["alpha"], beta_eat=w1["beta_eat"],
                                 beta=w1["beta"], tokens_per_check=w1["tokens_in"] + w1["tokens_out"])
                    for c in (1.0, 2.0):
                        e = effective_penalty(w1["alpha"], w1["beta_eat"], c)
                        entry[f"e_c{int(c)}"], entry[f"class_c{int(c)}"] = e, c1_class(e)
                    c1.append(entry)
    return rows, c1


def tables(rows, c1):
    out = ["# LLM inspector ladder: tables (generated by experiments/llm_overseer/analyze.py)", ""]
    out += ["α = misses on true violations (no verdict counts as a miss); β = false alarms on honest records; "
            "β_eat = false alarms on honest Harvest records with at least one apple taken. 95% Wilson intervals "
            "in brackets. Tokens are per check (in / out).", ""]
    out += ["## Harvest, pooled over windows (full subset: 90 violation and 90 honest records per rendering)", "",
            "| Model | Mode | Rendering | α | β | β_eat | said YES | no verdict | tokens in / out | s per check |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["dataset"] == "harvest" and r["group"] == "all":
            out.append(f"| {r['model']} | {r['mode']} | {r['rendering']} | {fmt(r['alpha'])} {ci(r['alpha_ci'])} | "
                       f"{fmt(r['beta'])} {ci(r['beta_ci'])} | {fmt(r['beta_eat'])} | {fmt(r['yes_rate'])} | "
                       f"{fmt(r['no_verdict'])} | {r['tokens_in']:.0f} / {r['tokens_out']:.0f} | {fmt(r['seconds'], 1)} |")
    out += ["", "## Harvest by window (full subset: 30 violation and 30 honest records per cell)", "",
            "| Model | Mode | Rendering | w | α | β | β_eat | α + β_eat | tokens in / out |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["dataset"] == "harvest" and r["group"] != "all":
            out.append(f"| {r['model']} | {r['mode']} | {r['rendering']} | {r['group'][1:]} | {fmt(r['alpha'])} | "
                       f"{fmt(r['beta'])} | {fmt(r['beta_eat'])} | {fmt(r['alpha'] + r['beta_eat'])} | "
                       f"{r['tokens_in']:.0f} / {r['tokens_out']:.0f} |")
    out += ["", "## C1 applied (w = 1 numbers, as in the RL runs)", "",
            "Effective average penalty e = (1 − α − β_eat)·c. Learners: every run at e ≤ 0.5 lost the orchard, "
            "every run at e ≥ 0.75 kept it.", "",
            "| Model | Mode | Rendering | α | β_eat | e at c = 1 | class | e at c = 2 | class | tokens per check |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for e in c1:
        out.append(f"| {e['model']} | {e['mode']} | {e['rendering']} | {fmt(e['alpha'])} | {fmt(e['beta_eat'])} | "
                   f"{fmt(e['e_c1'])} | {e['class_c1']} | {fmt(e['e_c2'])} | {e['class_c2']} | "
                   f"{e['tokens_per_check']:.0f} |")
    out += ["", "## BazaarBench: agreement with the GPT-5 labels (full subset: 60 unsafe and 60 safe per rendering)", "",
            "| Model | Mode | Rendering | α | β | α on reasoning-only failures | α on acted failures | said YES | "
            "no verdict | tokens in / out |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["dataset"] == "bazaar" and r["group"] == "all":
            out.append(f"| {r['model']} | {r['mode']} | {r['rendering']} | {fmt(r['alpha'])} {ci(r['alpha_ci'])} | "
                       f"{fmt(r['beta'])} {ci(r['beta_ci'])} | {fmt(r['alpha_reasoning_only'])} "
                       f"(of {r['n_reasoning_only']}) | {fmt(r['alpha_acted'])} (of {r['n_acted']}) | "
                       f"{fmt(r['yes_rate'])} | {fmt(r['no_verdict'])} | {r['tokens_in']:.0f} / {r['tokens_out']:.0f} |")
    out += ["", "## BazaarBench by failure type (full subset: 12 unsafe and 12 safe each)", "",
            "| Model | Mode | Rendering | type | α | β |", "|---|---|---|---|---|---|"]
    for r in rows:
        if r["dataset"] == "bazaar" and r["group"] != "all":
            out.append(f"| {r['model']} | {r['mode']} | {r['rendering']} | {r['group']} | {fmt(r['alpha'])} | "
                       f"{fmt(r['beta'])} |")
    out += ["", "## Confusion tables (true label : verdict; None = no YES/NO found)", "",
            "| Model | Mode | Dataset | Rendering | 1:YES | 1:NO | 1:None | 0:YES | 0:NO | 0:None |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["group"] == "all":
            c = r["confusion"]
            out.append(f"| {r['model']} | {r['mode']} | {r['dataset']} | {r['rendering']} | {c['1:1']} | {c['1:0']} | "
                       f"{c['1:None']} | {c['0:1']} | {c['0:0']} | {c['0:None']} |")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--judge-dir", default="results/llm_overseer/judge")
    ap.add_argument("--harvest", default="experiments/llm_overseer/data/harvest_judge.jsonl.gz")
    ap.add_argument("--bazaar", default="data/bazaarbench/llm_judge/bazaar_judge.jsonl.gz")
    ap.add_argument("--out", default="notes/llm_overseer/results")
    a = ap.parse_args()
    meta = {}
    for path in (a.harvest, a.bazaar):
        if Path(path).exists():
            for e in S.load_jsonl(path):
                meta[e["id"]] = {k: v for k, v in e.items() if k not in ("renderings", "label", "dataset")}
    rows, c1 = analyse(load_results(a.judge_dir, meta))
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tables.md").write_text(tables(rows, c1))
    models = {r["model"]: BY_TAG.get(r["model"], {}) for r in rows}
    (out / "summary.json").write_text(json.dumps(dict(rows=rows, c1=c1, models=models), indent=1, default=str))
    print((out / "tables.md").read_text())


if __name__ == "__main__":
    main()
